function flattenStrings(
  value: unknown,
  prefix = "",
  output: Record<string, string> = {},
): Record<string, string> {
  if (!value || typeof value !== "object" || Array.isArray(value)) return output;
  for (const [key, nested] of Object.entries(value)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof nested === "string") output[path] = nested;
    else flattenStrings(nested, path, output);
  }
  return output;
}

const catalogTranslationsCache: Partial<Record<ApiLanguage, Record<string, string>>> = {};

function findCatalogTranslation(source: string, language: ApiLanguage): string | undefined {
  const cached = catalogTranslationsCache[language];
  if (cached) return cached[source];

  const translations = Object.create(null) as Record<string, string>;
  for (const catalog of existingCatalogs) {
    if (!catalog || typeof catalog !== "object") continue;
    const localeCatalog = catalog as Record<string, unknown>;
    const sourceEntries = flattenStrings(localeCatalog.es);
    const targetEntries = flattenStrings(localeCatalog[language]);
    for (const [key, value] of Object.entries(sourceEntries)) {
      const translated = targetEntries[key];
      if (translated && !Object.prototype.hasOwnProperty.call(translations, value)) {
        translations[value] = translated;
      }
    }
  }
  catalogTranslationsCache[language] = translations;
  return translations[source];
}

