export function translateMobileCopy(
  source: string,
  variables: Record<string, string | number> = {},
): string {
  const language = getApiLanguage();
  const localeCopy = copy[language];
  const spanishCopy = copy.es;
  const template = (Object.prototype.hasOwnProperty.call(localeCopy, source) ? localeCopy[source] : undefined)
    ?? findCatalogTranslation(source, language)
    ?? (Object.prototype.hasOwnProperty.call(spanishCopy, source) ? spanishCopy[source] : undefined)
    ?? source;
  return template.replace(/\{\{([a-zA-Z0-9_]+)\}\}/g, (_match, key: string) =>
    String(variables[key] ?? ""),
  );
}

export function localizeMobileCatalogText(
  source: string | null | undefined,
  localized: Partial<Record<Exclude<ApiLanguage, "es">, string | null | undefined>>,
  language: ApiLanguage = getApiLanguage(),
): string {
  if (language !== "es") {
    const translated = localized[language]?.trim();
    if (translated) return translated;
  }
  const fallback = source ?? "";
  return fallback ? translateMobileCopy(fallback) : "";
}

